export function translatePortalText(text: string, language: PortalLanguage): string {
  if (language === 'English') return text;

  const dictionary = phrases[language];
  const trimmed = text.trim();
  const translation = dictionary[trimmed];
  if (!translation) return text;

  const leadingWhitespace = text.match(/^\s*/)?.[0] ?? '';
  const trailingWhitespace = text.match(/\s*$/)?.[0] ?? '';
  return `${leadingWhitespace}${translation}${trailingWhitespace}`;
}